import { readFile, readdir, access } from "node:fs/promises";
import { constants } from "node:fs";
import { extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseHtml, parseFragment } from "parse5";
import { parse as parseJs } from "acorn";
import { allExperiments } from "../src/data/experiments.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const publicDir = join(root, "public");
const errors = [];
const origin = "https://physics-lab.invalid";

async function filesWithin(dir) {
    const entries = await readdir(dir, { withFileTypes: true });
    return (await Promise.all(entries.map((item) => item.isDirectory()
        ? filesWithin(join(dir, item.name)) : [join(dir, item.name)]))).flat();
}
function walk(node, visit) {
    if (!node || typeof node !== "object") return;
    visit(node);
    for (const [key, child] of Object.entries(node)) {
        if (key === "parentNode") continue;
        if (Array.isArray(child)) child.forEach((item) => walk(item, visit));
        else if (child && typeof child === "object") walk(child, visit);
    }
}
function elements(document) {
    const result = [];
    walk(document, (node) => { if (node.tagName) result.push(node); });
    return result;
}
const attr = (node, name) => node.attrs?.find((item) => item.name === name)?.value;
const text = (node) => (node.childNodes || []).map((child) => child.value || "").join("");

async function checkResource(reference, sourceFile) {
    if (!reference || /^(?:data:|blob:|mailto:|tel:|javascript:|#)/i.test(reference)) return;
    let url;
    try {
        const base = "/" + relative(publicDir, sourceFile).split(sep).join("/");
        url = new URL(reference, origin + base);
    } catch { errors.push(`${relative(root, sourceFile)}: 无效资源地址 ${reference}`); return; }
    if (url.origin !== origin || url.pathname.startsWith("/api/")) return;
    let pathname;
    try { pathname = decodeURIComponent(url.pathname); }
    catch { errors.push(`${relative(root, sourceFile)}: 无效路径编码 ${reference}`); return; }
    if (pathname === "/") return; // The homepage is generated by Astro.
    const target = resolve(publicDir, "." + pathname);
    if (!target.startsWith(publicDir + sep)) {
        errors.push(`${relative(root, sourceFile)}: 资源路径越界 ${reference}`); return;
    }
    try { await access(target, constants.R_OK); }
    catch { errors.push(`${relative(root, sourceFile)}: 资源不存在 ${reference}`); }
}
async function checkCss(source, file) {
    for (const [, , reference] of source.matchAll(/url\(\s*(["']?)(.*?)\1\s*\)/g)) await checkResource(reference, file);
}
function syntaxTree(source, label, module = false) {
    try { return parseJs(source, { ecmaVersion: "latest", sourceType: module ? "module" : "script", locations: true }); }
    catch (error) { errors.push(`${label}: 脚本语法错误 (${error.message})`); return null; }
}
async function scriptResources(tree, file) {
    const references = [];
    walk(tree, (node) => {
        if (["ImportDeclaration", "ExportNamedDeclaration", "ExportAllDeclaration", "ImportExpression"].includes(node.type)
            && typeof node.source?.value === "string") references.push(node.source.value);
        if (node.type === "AssignmentExpression" && ["src", "href"].includes(node.left?.property?.name)
            && typeof node.right?.value === "string") references.push(node.right.value);
    });
    for (const reference of references) {
        if (/^(?:\.?\.?\/|https?:|\/)/.test(reference)) await checkResource(reference, file);
    }
}

const publicFiles = await filesWithin(publicDir);
const htmlFiles = publicFiles.filter((file) => extname(file) === ".html");
for (const item of allExperiments) {
    await checkResource(item.link, join(publicDir, "index.html"));
    if (item.image) await checkResource(item.image, join(publicDir, "index.html"));
}
for (const file of htmlFiles) {
    const source = await readFile(file, "utf8");
    const nodes = elements(parseHtml(source));
    const label = relative(publicDir, file);
    const ids = new Set();
    for (const node of nodes) {
        const id = attr(node, "id");
        if (!id) continue;
        if (ids.has(id)) errors.push(`${label}: 重复 id (${id})`);
        ids.add(id);
    }
    const required = [
        [nodes.some((node) => node.tagName === "title" && text(node).trim()), "缺少标题"],
        [nodes.some((node) => node.tagName === "meta" && attr(node, "name") === "viewport"), "缺少 viewport"],
        [nodes.some((node) => node.tagName === "canvas"), "缺少 Canvas"],
        [nodes.some((node) => node.tagName === "a" && attr(node, "href") === "/"), "缺少返回展厅入口"],
        [nodes.some((node) => node.tagName === "link" && attr(node, "href") === "/lab-common.css"), "未加载公共样式"],
        [nodes.some((node) => node.tagName === "script" && attr(node, "src") === "/lab-runtime.js"), "未加载公共运行时"],
    ];
    for (const [ok, message] of required) if (!ok) errors.push(`${label}: ${message}`);
    const trees = [];
    for (const node of nodes) {
        for (const name of ["src", "poster"]) if (attr(node, name)) await checkResource(attr(node, name), file);
        if (["a", "link"].includes(node.tagName)) await checkResource(attr(node, "href"), file);
        if (attr(node, "style")) await checkCss(attr(node, "style"), file);
        if (node.tagName === "style") await checkCss(text(node), file);
        for (const attribute of node.attrs || []) {
            if (/^on\w+/.test(attribute.name)) syntaxTree(`function eventHandler(event) {${attribute.value}\n}`, `${label}:${attribute.name}`);
        }
        if (node.tagName !== "script" || attr(node, "src")) continue;
        const type = attr(node, "type") || "text/javascript";
        if (["application/ld+json", "application/json"].includes(type)) {
            try { JSON.parse(text(node)); } catch { errors.push(`${label}: 无效 JSON 脚本`); }
            continue;
        }
        if (!["module", "text/javascript", "application/javascript"].includes(type)) continue;
        const tree = syntaxTree(text(node), label, type === "module");
        if (tree) { trees.push(tree); await scriptResources(tree, file); }
    }
    // Account for IDs created by inline markup and explicit element.id assignments.
    // Check literal IDs only; computed selectors/querySelectorAll may intentionally match nothing.
    const aliases = new Set();
    const stringArrays = new Map();
    for (const tree of trees) walk(tree, (node) => {
        if (node.type === "VariableDeclarator" && node.id?.type === "Identifier"
            && node.init?.type === "ArrayExpression" && node.init.elements.every((item) => typeof item?.value === "string")) {
            stringArrays.set(node.id.name, node.init.elements.map((item) => item.value));
        }
    });
    // Resolve markup IDs from finite literal loops, e.g. ['ax','ay'].forEach(id => `...id="${id}"...`).
    // An unresolved template never becomes a wildcard, so unrelated misspelled IDs still fail.
    for (const tree of trees) walk(tree, (node) => {
        if (node.type !== "CallExpression" || node.callee?.property?.name !== "forEach") return;
        const object = node.callee.object;
        const values = object?.type === "ArrayExpression" && object.elements.every((item) => typeof item?.value === "string")
            ? object.elements.map((item) => item.value) : stringArrays.get(object?.name);
        const callback = node.arguments?.[0];
        const parameter = callback?.params?.[0]?.name;
        if (!values || !parameter) return;
        walk(callback.body, (template) => {
            if (template.type !== "TemplateLiteral") return;
            const source = template.quasis.map((part, index) => part.value.cooked + (index < template.expressions.length ? `__EXPR_${index}__` : "")).join("");
            for (const [, pattern] of source.matchAll(/\bid\s*=\s*["']([^"']+)["']/g)) {
                for (const value of values) {
                    let resolved = true;
                    const id = pattern.replace(/__EXPR_(\d+)__/g, (_, index) => {
                        const expression = template.expressions[Number(index)];
                        if (expression.type === "Identifier" && expression.name === parameter) return value;
                        if (expression.type === "Literal") return String(expression.value);
                        resolved = false;
                        return "";
                    });
                    if (resolved) ids.add(id);
                }
            }
        });
    });
    for (const tree of trees) walk(tree, (node) => {
        if (node.type === "Literal" && typeof node.value === "string" && /<[^>]+\bid\s*=/.test(node.value)) {
            for (const element of elements(parseFragment(node.value))) if (attr(element, "id")) ids.add(attr(element, "id"));
        }
        if (node.type === "AssignmentExpression" && node.left?.property?.name === "id" && typeof node.right?.value === "string") ids.add(node.right.value);
        if (node.type === "VariableDeclarator" && node.id?.type === "Identifier" && node.init?.type === "ArrowFunctionExpression") {
            const body = node.init.body;
            if (body?.type === "CallExpression" && body.callee?.object?.name === "document" && body.callee?.property?.name === "getElementById") aliases.add(node.id.name);
        }
    });
    const missing = new Set();
    for (const tree of trees) walk(tree, (node) => {
        if (node.type !== "CallExpression" || typeof node.arguments?.[0]?.value !== "string") return;
        const callee = node.callee;
        const value = node.arguments[0].value;
        let id;
        if (callee.object?.name === "document" && callee.property?.name === "getElementById") id = value;
        else if (callee.type === "Identifier" && aliases.has(callee.name)) id = value;
        else if (callee.object?.name === "document" && callee.property?.name === "querySelector" && /^#[\w-]+$/.test(value)) id = value.slice(1);
        if (id && !ids.has(id)) missing.add(id);
    });
    for (const id of missing) errors.push(`${label}: 静态 DOM 引用不存在 (#${id})`);
}
for (const file of publicFiles) {
    if (extname(file) === ".css") await checkCss(await readFile(file, "utf8"), file);
    if (extname(file) === ".js") {
        const source = await readFile(file, "utf8");
        const tree = syntaxTree(source, relative(publicDir, file), /^\s*(?:import|export)\s/m.test(source));
        if (tree) await scriptResources(tree, file);
    }
}
if (errors.length) {
    console.error(errors.map((error) => `- ${error}`).join("\n"));
    process.exitCode = 1;
} else {
    console.log(`内容检查通过：${htmlFiles.length} 个页面，${allExperiments.length} 个清单条目，已检查内部资源、模块语法与静态 DOM 引用。`);
}
